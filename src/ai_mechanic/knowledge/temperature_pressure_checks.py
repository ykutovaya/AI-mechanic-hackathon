"""Подбирает первичные проверки системы охлаждения и системы смазки по руководству."""

import re

from .qdrant_chunks import clean
from .sources import verified_pdf_pages


_COMMON_MANUAL = "zmz-40904-40905-rk-2025"
_COMMON_ENGINES = {"ЗМЗ-40904.10", "ЗМЗ-40905.10"}


def select_dipstick_check(search, kind):
    """Берёт условия и действия одной процедуры проверки уровня масла."""
    if search.engine not in _COMMON_ENGINES:
        return False
    return search.passage(
        "Проверку уровня производить при нахождении автомобиля на ровной горизонтальной площадке через 5 минут "
        "вынуть указатель уровня масла",
        r"Проверку уровня производить при нахождении автомобиля на ровной горизонтальной площадке\. "
        r"После остановки двигателя или после доливки масла уровень следует проверять не ранее, чем через 5 минут, "
        r"чтобы масло успело стечь в масляный картер\. Для проверки уровня масла:\s*[–—-]\s*вынуть указатель "
        r"уровня масла;.{1,260}?снова вынуть указатель и проверить уровень масла на указателе\.",
        kind=kind,
        work="Проверить уровень масла указателем на ровной горизонтальной площадке не ранее чем через "
             "5 минут после остановки двигателя или доливки масла.",
    )


def select_cooling_checks(search, question, symptoms):
    """Отделяет осмотр по признакам перегрева от ремонта после подтверждения причины."""
    if search.engine == "ЯМЗ-236М2":
        if not (symptoms or ("ремн" in question and "радиатор" in question and "провер" in question)):
            return None
        work = "Проверить натяжение и целостность ремня водяного насоса."
        found_belt = search.passage(
            "Повышенная температура слабое натяжение или обрыв ремня водяного насоса",
            r"Слабое натяжение или обрыв (?:Натянуть ремень, если необходимо, )?ремня водяного насоса",
            explain=lambda _: work, work=work)
        work = "Осмотреть наружную поверхность сердцевины радиатора на загрязнение."
        found_radiator = search.passage(
            "Повышенная температура загрязнение внешней поверхности сердцевины радиатора",
            r"Загрязнение внешней поверхнос(?:ти |- ?Очистить сердцевину р\s*адиатора ти )сердцевины радиатора",
            explain=lambda _: work, work=work)
        if not found_belt:
            return "В найденных фрагментах не подтверждена проверка ремня водяного насоса."
        if not found_radiator:
            return "В найденных фрагментах не подтверждена проверка сердцевины радиатора."
        return ""
    if search.engine == "ЗМЗ-5234.10":
        if not (symptoms or ("теч" in question and "охлажд" in question and "провер" in question)):
            return None
        work = "Проверить, нет ли течи в соединениях шлангов, в сальниках водяного насоса и в радиаторе."
        found = search.passage(
            "Двигатель перегревается проверить нет ли течи в соединениях шлангов сальниках водяного насоса радиаторе",
            r"Недостаточное количество охлаждающей жидкости в системе охлаждения\s*\|\s*Долить жидкость, "
            r"проверить, нет ли течи в соединениях шлангов, в сальниках водяного насоса, радиатора",
            explain=lambda _: work, work=work)
        search.passage(
            "Пробуксовка ремня вентилятора отрегулировать натяжение ремня",
            r"Пробуксовка ремня вентилятора\s*\|\s*Отрегулировать натяжение ремня",
            explain=lambda _: "Если подтвердится пробуксовка ремня вентилятора, отрегулируйте его натяжение.")
        return "" if found else "В найденных фрагментах не подтверждена проверка течи системы охлаждения."
    return None


def asks_about_oil_indicator(engine, question):
    """Распознаёт вопрос о проверке стрелочного указателя и его датчика."""
    return (engine in _COMMON_ENGINES and re.search(r"провер|диагност", question)
            and "указател" in question and "датчик" in question and "давлен" in question and "масл" in question)


def add_oil_indicator_evidence(result, registry, root, engine):
    """Проверяет условия двух электрических тестов на физических страницах одной редакции."""
    if engine not in _COMMON_ENGINES:
        return
    pages = verified_pdf_pages(registry, root, _COMMON_MANUAL, engine, (89, 110, 111))
    evidence = _indicator_sections(pages.values(), engine)
    if evidence:
        result["evidence"].extend(evidence)
        result["missing"] = ""


def select_indexed_oil_indicator(search):
    """Берёт обе части проверки из фрагментов одной редакции и проверяет вариант оборудования."""
    hits = search.find("Датчик указателя давления масла устанавливается на часть двигателей. Проверка: "
                       "если стрелка в конце шкалы при включении зажигания и неработающем холодном двигателе")
    evidence = _indicator_sections(hits, search.engine)
    search.evidence.extend(evidence)
    return bool(evidence)


def _indicator_sections(hits, engine):
    patterns = {
        89: r"Датчик указателя давления масла 23\.3829010 \(рис\.\s*78\) устанавливается на часть двигателей\.",
        110: r"Если при включении зажигания и неработающем, холодном двигателе "
             r"\(при этом контрольная лампа аварийного давления масла должна гореть\) стрелка указателя "
             r"находится в конце шкалы или показывает давление больше 0 кгс/см[2²],.{1,190}?"
             r"Для установления причины следует отсоединить провод от датчика\. "
             r"Если неисправен датчик и нет замыкания на массу, стрелка должна",
        111: r"вернуться в начало шкалы\. Если стрелка указателя после запуска и при работе двигателя постоянно "
             r"находится в начале шкалы \(при этом контрольная лампа аварийного давления масла не горит\),"
             r".{1,185}?Для проверки следует отсоединить провод от датчика и замкнуть его на массу\. "
             r"Если неисправен датчик, стрелка должна перемести[тть]+ся в правый конец шкалы\.",
    }
    statements = {
        89: "Уточните, установлен ли стрелочный указатель давления масла и его датчик. "
            "Датчик 23.3829010 устанавливается только на часть двигателей.",
        110: "Если на холодном остановленном двигателе при включённом зажигании лампа горит, "
             "а стрелка в конце шкалы или показывает больше нуля, отсоедините провод от датчика указателя.",
        111: "При неисправном датчике и отсутствии замыкания на массу стрелка должна вернуться в начало шкалы. "
             "Другой случай: если при работе двигателя стрелка остаётся в начале шкалы, а аварийная лампа не горит, "
             "отсоедините провод от датчика и замкните провод на массу. При неисправном датчике стрелка должна "
             "переместиться в правый конец шкалы.",
    }
    by_edition = {}
    for hit in hits:
        page = hit["page"]
        if (page not in patterns or hit["document_id"] != _COMMON_MANUAL or engine not in hit["engine_models"]
                or not hit.get("source_sha256")):
            continue
        match = re.search(patterns[page], clean(hit["text"]), re.I)
        if match:
            parts = by_edition.setdefault((hit["source_sha256"], hit["edition"]), {})
            parts[page] = dict(hit, applicability=hit.get("applicability", [f"{engine}|all"]),
                               text=statements[page], excerpt=match.group(), kind="fact", required=True, work=None, lamp=False)
            if len(parts) == len(patterns):
                return [parts[n] for n in patterns]
    return []
